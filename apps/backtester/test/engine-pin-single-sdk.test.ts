// S3 шаг 1 — точный пин на `@trdlabs/engine` и ОДНА копия контракта в дереве.
//
// ЗАЧЕМ ЭТО ТЕСТ, А НЕ ЗАПИСЬ В ОТЧЁТЕ. «Проверил — одна копия» верно ровно в день проверки.
// Вторая копия появляется не от правки этого файла: движок пинит `@trdlabs/sdk` ТОЧНОЙ версией, а
// здешние манифесты — КАРЕТНЫМ диапазоном. Пока в минорной ветке контракта одна опубликованная
// версия, обе стороны сходятся на ней.
//
// ТОЧНО О МОМЕНТЕ, потому что здесь легко сказать сильнее, чем есть. Сама публикация следующего
// патча контракта установленного дерева НЕ меняет: `--frozen-lockfile` ставит ровно то, что
// записано. Копий станет две при следующем ОБНОВЛЕНИИ lockfile, которое переразрешит диапазон, —
// то есть при добавлении любой зависимости или плановом апдейте, в коммите, который к движку
// отношения не имеет и в ревью выглядит безобидно. Гейт падает именно там, и это правильный
// момент: раньше падать не на чем, позже — уже в сборке потребителя.
//
// НОМЕРА ВЕРСИЙ ЖИВУТ ТОЛЬКО В УТВЕРЖДЕНИЯХ. В прозе их нет намеренно: при первом же бампе
// комментарий с числом начинает называть то, чего в файле уже нет, — и читатель верит комментарию,
// потому что он подробнее.
//
// ПОЧЕМУ ДВЕ КОПИИ — ЭТО ПОЛОМКА, А НЕ ЛИШНИЕ БАЙТЫ. Брендированные µs-типы контракта номинальны:
// их идентичность есть место объявления. Две копии пакета дают два РАЗНЫХ типа, которые перестают
// присваиваться друг другу, и обнаруживается это сборкой потребителя в момент, когда никто не
// менял ни движок, ни бэктестер.
//
// Гейт поэтому смотрит на УСТАНОВЛЕННОЕ дерево, а не на манифесты: манифесты говорят о намерении,
// дерево — о факте.

import { describe, expect, it } from 'vitest';
import { readFileSync, realpathSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP_MANIFEST = resolve(HERE, '../package.json');

const manifest = JSON.parse(readFileSync(APP_MANIFEST, 'utf8')) as {
  dependencies: Record<string, string>;
};

describe('S3: пин движка', () => {
  it('движок пиннится ТОЧНОЙ версией, а не диапазоном', () => {
    // Диапазон на движке означал бы, что актор-поверхность и формат trace могут поменяться под
    // ногами между двумя установками, а голдены заякорены на конкретное поведение.
    expect(manifest.dependencies['@trdlabs/engine']).toMatch(/^\d+\.\d+\.\d+$/);
  });

  it('пин — та версия движка, что несёт нужную поверхность и нужный контракт', () => {
    // История, по которой пин доехал сюда, и она объясняет, почему число обязано быть точным:
    //   0.3.0 — пинит прежний контракт и не несёт актор-поверхности вовсе;
    //   0.4.0 — актор-ядро есть, но гейт границы сообщался отдельными вызовами open/close;
    //   0.5.0 — оркестратор есть, но ТОЛЬКО синхронный, а барный цикл здесь асинхронен по
    //           существу: стратегия исполняется за границей песочницы;
    //   0.6.0 — первая версия, которую можно надеть на этот цикл;
    //   0.7.0 — она же на контракте с `unsupported_lifecycle` (083 S3);
    //   0.8.0 — деривация сделок актора из журнала бухгалтерии: без неё проекция вынуждена была бы
    //           принимать готовый `Trade` от раннера, ничем не привязанный к филлам;
    //   0.9.0 — три хвоста parity с legacy: `closeSeq` по эре, апорционирование по запрошенной
    //           доле, аннотации закрытия как точное множество;
    //   0.10.0 — заявленная доля обязана совпадать с исполненным объёмом: без этой проверки
    //           противоречивая пара разносила комиссию входа мимо своей доли, а тождество
    //           сходимости к разбиению нечувствительно и оставалось зелёным;
    //   0.11.0 — каноническая величина сверки (`canonicalRealizedPnl`). Прежняя сводка лежит на
    //           другой решётке округления, и на настоящих числах прогона гейт `Object.is`
    //           отвергал корректный результат. Допуск запрещён решением владельца — вместо него
    //           величина, равная леджеру побитово по построению.
    //   0.12.0 — репин контракта под host-source union и нотионал-первичный вид заявки: без него
    //           канонический хостовый источник отсюда не выразим, а `qtyUsd` не существует;
    //   0.13.0 — матчинг РАЗДЕЛЁН на две фазы: `matchBar` отвечает «какая заявка и по какой цене»,
    //           размер во второй. Прежняя форма несла `qty` в стоящей заявке, и хост обязан был
    //           выдумать базовый размер ДО того, как узнал цену исполнения;
    //   0.14.0 — исполнение стало ОДНОЙ операцией `executeFill`: размер, нотионал, комиссия и факт
    //           клампа приходят вместе. Композиция из трёх примитивов оставляла потребителю
    //           программу из трёх решений, и порядок в ней менял последние разряды;
    //   0.15.0 — операция возвращает `executionPrice`. Без неё хост пересчитывал цену теми же
    //           параметрами повторно, и рассинхронизация `dir`/`bps` не была бы замечена ничем;
    //   0.16.0 — исход ДИСКРИМИНИРОВАН: `canceled` вместо нулевого филла. Нулевой размер доезжал
    //           до `applyFill` и ронял прогон броском вместо того, чтобы означать снятие заявки;
    //   0.17.0 — остаток позиции передаётся ЗНАКОВЫМ, и причин снятия две. Прежний `sizeCap`
    //           требовал от хоста самому сравнить стороны, а это схлопывало «позиции нет» и
    //           «позиция перевернулась» в один вход: движок отвечал на оба словом `flat`, что для
    //           второго случая неправда. Пин точен именно ради таких смен: диапазон подменил бы
    //           семантику причины между двумя установками, не тронув ни строки здесь.
    //
    // Число живёт ТОЛЬКО в утверждении ниже. В прозе его нет намеренно: комментарий, называющий
    // версию, переживает первый же подъём и начинает врать подробно — а подробному верят.
    expect(manifest.dependencies['@trdlabs/engine']).toBe('0.17.0');
  });

  it('установленный движок — та же версия, что заявлена', () => {
    // Манифест говорит о намерении; спрашиваем факт.
    const installed = JSON.parse(
      readFileSync(resolve(HERE, '../node_modules/@trdlabs/engine/package.json'), 'utf8'),
    ) as { version: string };
    expect(installed.version).toBe(manifest.dependencies['@trdlabs/engine']);
  });
});

describe('S3: ровно одна копия контракта в дереве', () => {
  // ЧТО ИМЕННО МЕРИТЬ — тут легко ошибиться, и первая редакция ошиблась. Она считала каталоги
  // `node_modules/.pnpm/@trdlabs+sdk@*`, то есть СТОР. Стор хранит и то, что установкой больше не
  // используется: после переключения версии туда-обратно устаревшая запись остаётся лежать, и гейт
  // краснел на дереве, где разрешение давно одно. «Пакет присутствует на диске» и «дерево его
  // использует» — разные утверждения, и нужно второе.
  //
  // Здесь берётся то, что определяет ТИПЫ: физический каталог, в который упирается разрешение с
  // двух сторон — из приложения и из установленного движка. Совпали пути — место объявления
  // брендированных µs-типов одно, и они присваиваются. Разошлись — это два разных типа, что бы ни
  // говорили номера версий.

  const appSdkDir = (): string => realpathSync(resolve(HERE, '../node_modules/@trdlabs/sdk'));

  /** Контракт, каким его видит УСТАНОВЛЕННЫЙ движок: его зависимости лежат рядом с ним самим. */
  const engineSdkDir = (): string => {
    const engine = realpathSync(resolve(HERE, '../node_modules/@trdlabs/engine'));
    return realpathSync(join(dirname(dirname(engine)), '@trdlabs', 'sdk'));
  };

  it('приложение и движок упираются в ОДИН каталог контракта', () => {
    // Главное утверждение среза. Сообщение об отказе печатает оба пути: «не равно» без них
    // отправляет читателя выяснять заново то, что гейт уже знал.
    expect(`app: ${appSdkDir()}`).toBe(`app: ${engineSdkDir()}`);
  });

  it('этот каталог — ожидаемая версия контракта', () => {
    // «Один каталог» без «той самой версии» прошло бы и на дереве, где обе стороны одинаково
    // устарели.
    const version = (JSON.parse(readFileSync(join(appSdkDir(), 'package.json'), 'utf8')) as {
      version: string;
    }).version;
    expect(version).toBe('0.19.0');
  });

  it('диапазон приложения разрешается в ТОЧНЫЙ пин движка', () => {
    // Причина, по которой копия одна, названа проверяемо. Движок пинит ТОЧНО, приложение —
    // каретным диапазоном; сегодня они сходятся, потому что в этой минорной ветке контракта
    // опубликована одна версия. Разведёт их не публикация следующего патча сама по себе (frozen
    // lockfile ставит записанное), а первое ОБНОВЛЕНИЕ lockfile после неё — в чужом коммите,
    // который движка не касается. Тогда упадёт этот тест, а не сборка потребителя.
    const enginePin = (
      JSON.parse(readFileSync(resolve(HERE, '../node_modules/@trdlabs/engine/package.json'), 'utf8')) as {
        dependencies: Record<string, string>;
      }
    ).dependencies['@trdlabs/sdk'];
    const installed = (JSON.parse(readFileSync(join(appSdkDir(), 'package.json'), 'utf8')) as {
      version: string;
    }).version;

    expect(installed).toBe(enginePin);
    expect(manifest.dependencies['@trdlabs/sdk'].replace(/^[\^~]/, '')).toBe(enginePin);
  });
});
