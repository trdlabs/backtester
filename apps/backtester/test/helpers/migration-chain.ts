// Единственное объявление цепи миграций result-голденов — и правило, кто владеет их файлами.
//
// Зачем это существует. Голдены перебазируются звеньями, каждое со своим дериватором и своей
// hash-map. Файлы голденов при этом ОБЩИЕ: их три на всю цепь. Значит владелец у них может быть
// только один — последнее звено, чей `active` и лежит на диске. Любой другой дериватор, записав
// туда свой `active`, откатит голдены в свою эпоху.
//
// Это не гипотеза. 083 S1 добавил четвёртое звено, и `derive-f3-goldens --write` начал успешно
// записывать в файлы хеши эпохи Ф3 поверх 017.4. Причём ровно потому, что предыдущая правка
// ПОЧИНИЛА его проверку эквивалентности: до неё скрипт падал на несошедшемся якоре и не писал
// ничего, после — стал проходить и писать устаревшее. Починка одного гейта включила запись,
// которую никто не пересматривал.
//
// Отсюда форма защиты. Не «не забыть проверить» в каждом дериваторе, а объявленный порядок звеньев
// в одном месте: голова выводится из него, а не помнится. Когда появится 017.5, достаточно
// дописать строку — и `derive-017-4-goldens` начнёт отказываться от записи файлов САМ, без правки
// своего кода и без того, чтобы кто-то об этом вспомнил.

/** Одно звено цепи: идентификатор и путь к его mapping-фикстуре относительно корня репозитория. */
export interface MigrationLink {
  readonly id: string;
  readonly map: string;
}

/**
 * Звенья в порядке применения. Последнее — голова цепи; её `active` лежит в файлах голденов.
 *
 * Порядок здесь нормативен: `assertOwnsGoldenFiles` выводит владельца из него, и добавление нового
 * звена в конец автоматически снимает право записи с прежней головы.
 */
export const MIGRATION_CHAIN: readonly MigrationLink[] = [
  { id: '017-migration', map: 'apps/backtester/test/fixtures/017-migration/hash-map.json' },
  { id: 'f3-engine-migration', map: 'apps/backtester/test/fixtures/f3-engine-migration/hash-map.json' },
  { id: '017-4-migration', map: 'apps/backtester/test/fixtures/017-4-migration/hash-map.json' },
  { id: '017-5-migration', map: 'apps/backtester/test/fixtures/017-5-migration/hash-map.json' },
];

/** Голова цепи — единственное звено, которому разрешено писать в файлы голденов. */
export const CHAIN_HEAD: MigrationLink = MIGRATION_CHAIN[MIGRATION_CHAIN.length - 1] as MigrationLink;

/** Пара якорей одного звена для одного сценария: откуда звено ушло и куда пришло. */
export interface LinkAnchors {
  readonly id: string;
  readonly legacy: string;
  readonly active: string;
}

/**
 * Якоря ВСЕХ звеньев цепи для одного сценария, в порядке применения.
 *
 * Существует потому, что сцепку звеньев каждый исторический пруф прежде выписывал у себя руками:
 * читал карту «следующего» звена по зашитому пути и сравнивал файл на диске с её `active`. Пока
 * звено было последним, это работало; добавление 017.5 сделало «следующего» соседа не головой, и
 * ТРИ пруфа разом стали утверждать неправду про диск — притом что сама цепь не рвалась.
 *
 * Здесь порядок и состав берутся из `MIGRATION_CHAIN`, то есть из одного объявления. Новое звено —
 * одна строка там, и ни один пруф править не нужно.
 */
export function chainAnchors(
  repoRoot: string,
  scenarioId: string,
  readJson: (path: string) => unknown,
): readonly LinkAnchors[] {
  return MIGRATION_CHAIN.map((link) => {
    const map = readJson(`${repoRoot}/${link.map}`) as {
      goldens?: Record<string, { legacy?: string; active?: string }>;
    };
    const entry = map.goldens?.[scenarioId];
    if (entry?.legacy === undefined || entry.active === undefined) {
      throw new Error(
        `migration-chain: в карте звена '${link.id}' нет якорей сценария '${scenarioId}'. ` +
          `Звено, не знающее сценария, разрывает цепь молча.`,
      );
    }
    return { id: link.id, legacy: entry.legacy, active: entry.active };
  });
}

/**
 * Разрешить записывать файлы голденов только голове цепи. Бросает — то есть fail-closed — для
 * любого исторического звена.
 *
 * Отказ намеренно НЕ мягкий (не предупреждение и не пропуск записи молча): дериватор, который
 * «успешно отработал, но ничего не записал», читается оператором как «всё в порядке», а это
 * ровно тот исход, которого здесь нельзя допускать.
 */
export function assertOwnsGoldenFiles(linkId: string): void {
  const known = MIGRATION_CHAIN.some((l) => l.id === linkId);
  if (!known) {
    throw new Error(
      `migration-chain: звено '${linkId}' не объявлено в MIGRATION_CHAIN. ` +
        `Дериватор без записи в цепи не может знать, голова он или нет — допиши строку.`,
    );
  }
  if (linkId !== CHAIN_HEAD.id) {
    throw new Error(
      `migration-chain: звено '${linkId}' больше не голова цепи и файлами голденов НЕ владеет.\n` +
        `  Голова сейчас: '${CHAIN_HEAD.id}' (${CHAIN_HEAD.map}).\n` +
        `  Запись отсюда откатила бы голдены в эпоху '${linkId}': файлы общие на всю цепь.\n` +
        `  Если голдены действительно надо перебазировать — это делает дериватор головы.\n` +
        `  Проверочный (без --write) режим этого звена по-прежнему осмыслен и остаётся доступен.`,
    );
  }
}
