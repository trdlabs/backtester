// 083 S3 — THREAD E2E: actor-прогон ПРОД-ДОРОГОЙ. Срез вскрыл блокер, и файл фиксирует ЕГО.
//
// ═══ ЧТО СОБИРАЛИСЬ ДОКАЗАТЬ ═══
//
// Паритет прод-дороги с direct: тот же терминальный исход, те же артефакты, тот же timeline hash.
// Дорога здесь настоящая — HTTP `POST /v1/runs` → очередь → воркер → sandbox-исполнитель → строка
// в хранилище, — и между ней и `runBacktest` лежит всё, что можно потерять молча: конфиг →
// `WorkerDeps` → `StrategyRunDeps` → `RunDeps`, сериализация запроса, выбор исполнителя, поток со
// своим графом модулей.
//
// ═══ ЧТО ВЫЯСНИЛОСЬ ВМЕСТО ЭТОГО ═══
//
// ПРОД-ДОРОГА ЗАКРЫТА ПРОИСХОЖДЕНИЕМ СВЕЧЕЙ. Это уже ТРЕТЬЯ причина подряд, и каждая предыдущая
// была снята срезом:
//
//   1. РИСК — до риск-среза `DEFAULT_RISK` объявлял лимиты, которых actor-путь не соблюдал, и
//      допуск отказывал fail-closed. Теперь профиль ИСПОЛНЯЕТСЯ (`risk.ts`);
//   2. СПОСОБНОСТЬ ИСПОЛНИТЕЛЯ — выбранный для прогона sandbox-исполнитель не умел lifecycle
//      актора. Теперь умеет по обе стороны границы (`isolate-executor.ts` + `actor-harness.mjs`),
//      и паритет с прямой дорогой доказан побайтово (`actor-boundary-parity`);
//   3. ПРОИСХОЖДЕНИЕ СВЕЧЕЙ — то, на чём дорога стоит СЕЙЧАС.
//
// ПРИЧИНА ТРЕТЬЕГО ОТКАЗА НЕ ТА, ЧТО КАЖЕТСЯ, И ЭТО ЗАПИСАНО ЗДЕСЬ ЯВНО. Фикстура
// `actor-thread-1m` происхождение ОБЪЯВЛЯЕТ (`candleVenue: "binance"`), и прямая дорога это
// заявление читает: `loadCandleDataset` кладёт поле в `CandleDataset`, и `actor-boundary-parity`
// на нём доезжает до конца. Дорога очереди строит ленту иначе — `buildOverlayDataset` →
// `MarketTapeDataset`, — и там поля нет: `FixtureDataPort` отдаёт `candleVenue` только в
// `listDatasets()`, то есть в ОПИСАНИИ датасета, а не в ленте, по которой идёт прогон.
//
// То есть два читателя одного заявления отвечают на него по-разному. Это НЕ снимает rollout-блокер
// cc#365 и не является им: у настоящих записанных данных происхождения нет ВОВСЕ — рекордер знал
// венью в момент записи и выбросил его, — поэтому проброс поля ничего не открыл бы реальной ленте.
// Он открыл бы ровно то, что уже объявлено фикстурой. Решение о таком пробросе принимает владелец:
// прод-дорога — часть контура раскатки, и снимать с неё условие молча, попутно, из теста нельзя.
//
// Пока решения нет, файл фиксирует ФАКТИЧЕСКОЕ состояние и стережёт снятый блокер: отказ обязан НЕ
// называть способность исполнителя. Причина, пережившая свою отмену, отправляла бы оператора чинить
// работающее.
//
// ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ФАЙЛА УТВЕРЖДАЛА ШИРЕ И ПОТОМУ НЕТОЧНО: «все пять профилей». Пять — это
// список ЭКСПОРТОВ `profiles.ts`; четыре из них (`DCA_RISK`, `TIGHT_ADD_RISK`, `LONG_ONLY_RISK`,
// `TIGHT_STOP_RISK`) в реестр не входят и через прод-дорогу недостижимы вовсе. Гейт при этом
// проходил — каждое отдельное утверждение было истинным, ложной была картина, которую они рисуют
// вместе. Инвентарь обязан читаться из того же источника, из которого прогон берёт профиль.
//
// ═══ ДОЛГ, КОТОРЫЙ ЭТОТ ФАЙЛ КОГДА-ТО НАЗВАЛ, ЗАКРЫТ ═══
//
// `actor-e2e-direct` был зелен на профиле `NO_LIMITS`, сконструированном самим тестом и в реестре
// отсутствующем, — то есть доказывал семантику на конфигурации, недостижимой в проде. Риск-срез
// перевёл его на настоящий `default_risk@1.0.0`, и «сквозной прогон проходит» теперь читается
// ровно так, как есть.
//
// Файл по-прежнему не обходит оставшийся блокер подставным исполнителем: подставить его значило бы
// доказать паритет двух дорог на состоянии, в которое прод попасть не может.

