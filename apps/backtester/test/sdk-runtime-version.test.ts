// Версия контракта, которая РЕАЛЬНО загружена в рантайме, а не та, что записана в манифесте.
//
// Манифест говорит о намерении, `node_modules` — о факте, и разойтись они могут молча: каретный
// диапазон переразрешается при любом обновлении lockfile. Поэтому утверждение читает константу из
// загруженного модуля.
//
// Номер держится в ОДНОМ месте — в утверждении. В заголовке теста его нет намеренно: он пережил
// подъём 0.13 → 0.14 в тексте «uses @trdlabs/sdk 0.14.0», и при следующем бампе назвал бы версию,
// которой в файле уже нет.
import { SDK_VERSION } from '@trdlabs/sdk';
import { expect, test } from 'vitest';

test('в рантайме загружена ожидаемая версия @trdlabs/sdk', () => {
  expect(SDK_VERSION).toBe('0.22.0');
});
