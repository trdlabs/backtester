--
-- ЗАЧЕМ. `terminal_code` отвечает на вопрос «какого рода отказ», и для всей прежней таксономии
-- этого хватало: `missing_dataset`, `run_deadline_exceeded`, `lease_expired` — каждый код и есть
-- причина целиком. `validation_error` устроен иначе: он объединяет десятки разных отказов, и без
-- подробности оператор видит слово, из которого не следует ничего.
--
-- Конкретный повод — 083: отказ `unsupported_lifecycle` не отличим в строке задания от любой другой
-- невалидности, хотя чинят их разные люди («раскатка выключена здесь» — операторская проблема,
-- «манифест противоречит сам себе» — авторская). Подробность жила только в бро́шенном `RunnerError`
-- и до хранилища не доезжала.
--
-- JSONB, а не текст: это `ValidationIssue[]` контракта — `code`, `message`, `path`, — и хранить их
-- склеенной строкой значило бы заставить каждого читателя разбирать её обратно, каждого по-своему.
-- Пустой JSON Pointer (`path: ''`) нормативен для причины без нарушающего узла и обязан доживать
-- ключом, а не исчезать: `jsonb` пустую строку сохраняет, склейка в текст потеряла бы её молча.

ALTER TABLE backtest_job ADD COLUMN IF NOT EXISTS terminal_issues_json JSONB;
