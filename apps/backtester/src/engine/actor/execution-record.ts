// 083 S3 — ЯВНЫЙ АГРЕГАТ ВХОДНЫХ ДАННЫХ проекции «actor execution → артефакты прогона».
//
// ═══ ЗАЧЕМ ЭТОТ ТИП ВООБЩЕ СУЩЕСТВУЕТ ═══
//
// Напрашивался другой ответ: «проекция читает execution ledger». Ledger объявлен SSOT бухгалтерии
// (§3.7), и казалось, что артефакты прогона — его производная. Сверка форм это ОПРОВЕРГЛА, и
// опровергла по всем семи семействам, которые обязан заполнить прогон.
//
// Артефакты несут факты ЧЕТЫРЁХ разных природ, и журнал исполнений — только одна из них:
//
//   1. бухгалтерские    — экспозиция, avgPrice, realizedPnl. ЭТО ledger даёт, и только это.
//   2. модели исполнения — цена до проскальзывания и сам bps. Существуют в момент матчинга и
//                          нигде не сохраняются: ledger видит уже исполненную цену.
//   3. хостовой политики — вердикты RiskEngine, причина закрытия. Ledger про них не знает по
//                          построению: §3.5 держит RiskEngine на стороне хоста.
//   4. пербарные        — equity как mark-to-market. Журнал разрежен по событиям, кривая обязана
//                          быть на каждом баре.
//
// Вывести (2)–(4) из (1) нельзя. Обратная арифметика вида `baseOpen = price / (1 ± bps/1e4)`
// технически считается, но это ИЗОБРЕТЁННАЯ точность: деление вносит ошибку округления, которой в
// исходных числах не было, и зашивает допущение о мультипликативной модели проскальзывания.
//
// Отсюда роль этого типа: он НЕ контейнер для удобства проектора. Он — СПИСОК ОБЯЗАТЕЛЬСТВ
// ГОРЯЧЕГО РАННЕРА: каждое поле называет факт, который раннер обязан записать в тот момент, когда
// факт ещё существует. Что не записано здесь — потеряно навсегда, и проекция это обнаружит отказом,
// а не догадкой.
//
// ═══ ОДИН ЖУРНАЛ, А НЕ ДВА СПИСКА ═══
//
// Филлы и funding-расчёты лежат в ОДНОЙ последовательности. Первая редакция держала их порознь, и
// это было неверно: апорционирование funding по закрываемой доле зависит от того, в каком порядке
// он чередовался с филлами, а два списка это знание не несут — его пришлось бы восстанавливать
// правилом склейки на стороне проектора. Правило склейки и есть то, что расходится: раннер применил
// в одном порядке, проектор склеил в другом, числа разошлись в последнем разряде.
//
// Порядок записей и есть порядок применения. Движок сворачивает ровно его (`deriveActorTrades`).
//
// ═══ ПОЛНЫЙ MAPPING (зафиксирован до реализации, требование владельца 2026-08-12) ═══
//
// | артефакт `RunOutcome`        | источник                          | достаточен ли ledger |
// | ---------------------------- | --------------------------------- | -------------------- |
// | `SimulatedOrder`             | `ActorOrderRecord`                | НЕТ — заявка без филлов не оставляет в журнале следа вовсе |
// | `SimulatedFill`              | записи журнала вида `fill`        | НЕТ — нет `baseOpen`, `slippageBps`, барного индекса |
// | `Trade`                      | `deriveActorTrades` + `ActorCloseAnnotation` | НЕТ — см. ниже |
// | `DecisionRecord`             | — (пусто на actor-пути)           | неприменимо — другой словарь, см. ниже |
// | `RiskDecision`               | `riskDecisions`                   | НЕТ — ledger про хостовую политику не знает |
// | `EquityPoint`                | `ActorEquitySample`               | НЕТ — нужна нереализованная часть на КАЖДОМ баре |
// | `FundingLedgerEntry`         | записи журнала вида `funding`     | НЕТ — движковый `applyFunding` складывает `cost` в `realizedPnl` и записи не оставляет |
//
// **`Trade` НЕ приносится готовым и НЕ пересчитывается хостом.** Сделку выводит движок из журнала
// (`deriveActorTrades`), а хост приносит ровно то, чего не знает больше никто, — ПРИЧИНУ закрытия,
// привязанную к закрывающему филлу по идентификатору. Готовая сделка на входе была бы ничем не
// привязанным набором чисел: раннер мог бы записать любые. Самостоятельный пересчёт в хосте завёл
// бы второй интерпретатор бухгалтерии — то, ради прекращения чего существует `@trdlabs/engine`.
//
// **`DecisionRecord` на actor-пути пуст, и это НЕ пропуск.** У актора `onEvent → ActorCommand[]`, у
// legacy `hook → StrategyDecision` — разные словари, а расширение общей формы видят голдены и
// comparison. Пофронтирная запись живёт не там: её носитель — `timeline`, отдельный append-only
// поток диспетчеризации со своей проекцией и своими гардами (`timeline.ts`). Он не расширяет
// legacy-форму и потому ничего в ней не двигает.

import type { CloseAnnotation, Fill, FillSide, Ledger, OrderState, RiskDecision } from '@trdlabs/engine';
import type { ActorSubscriptionDescriptor, TimestampUs } from '@trdlabs/sdk/research-contract';

import type { ActorTimeline } from './timeline.js';

/**
 * Один frontier — один business-момент `U` для одного инстанса актора (§3.8).
 *
 * Играет роль ОСИ всего агрегата: артефакты бэктестера адресуются барным индексом (`barIndex`) и
 * миллисекундной меткой, а актор живёт в µs и в номерах frontier'ов. Хранить у каждой записи свой
 * `barIndex` и свой `ts` значило бы дать двум записям возможность разойтись в том, какой это был
 * бар. Здесь ось одна, и все остальные записи ссылаются на неё номером.
 */
export interface ActorFrontierRecord {
  /** 0-based, монотонно возрастает с шагом 1. Становится `barIndex` артефакта напрямую. */
  readonly index: number;
  /** Business-время `U`. Метка строится ТОЛЬКО через `timestampUsFromMillis` (требование S3). */
  readonly tsUs: TimestampUs;
  /**
   * Последний `seq`, эффекты которого зафиксированы на конец этого frontier'а.
   *
   * Проекция проверяет по нему РОВНО одно: значение не убывает от frontier'а к frontier'у.
   * Убывание означает, что раннер переиграл уже применённые события.
   *
   * Непрерывность actor-local `seq` (§3.5) отсюда НЕ следует и здесь не доказывается: видны только
   * конечные точки, а пропуск внутри frontier'а конечную точку не двигает. Непрерывность —
   * предмет gap/duplicate гарда на стороне раннера, где виден сам поток событий.
   */
  readonly lastCommittedSeq: number;
}

/**
 * Одна поданная заявка — записывается в момент подачи, когда команда актора уже допущена.
 *
 * `terminalState` — состояние ордер-FSM на конец прогона, а не «статус». Сужение семи состояний
 * автомата до трёх статусов артефакта делает ПРОЕКЦИЯ, в одном месте и по таблице, которую видно
 * (см. `ORDER_STATUS_BY_STATE`). Записывать сюда уже суженное значение значило бы потерять
 * различие «отвергнута» и «отменена» до того, как кто-либо решил, что оно не нужно.
 */
export interface ActorOrderRecord {
  readonly orderId: string;
  /** Номер frontier'а, на котором заявка подана. */
  readonly placedAtFrontier: number;
  readonly side: 'long' | 'short';
  readonly intent: 'open' | 'close' | 'add';
  readonly terminalState: OrderState;
  readonly mode?: 'dca' | 'scale_in';
  readonly closeFraction?: number;
  readonly origin?: 'protection';
}

/**
 * Исполнение в журнале — записывается моделью исполнения в момент матчинга.
 *
 * `baseOpen` и `slippageBps` живут ТОЛЬКО здесь. Это и есть главная причина, по которой ledger'а
 * недостаточно: он видит `price` уже после применения проскальзывания, а обе исходные величины к
 * этому моменту перестали существовать.
 *
 * Артефактный вид филла назван `fillKind`, а не `kind`: `kind` здесь занят дискриминантом журнала,
 * и совпадение имён сделало бы союз неразличимым.
 */
export interface ActorJournalFill {
  readonly kind: 'fill';
  readonly frontier: number;
  readonly fillId: string;
  /** Заявка, которую исполняет этот филл («fills by causation», §3.7). */
  readonly orderId: string;
  readonly tsUs: TimestampUs;
  /** Цена исполнения — ПОСЛЕ проскальзывания. */
  readonly price: number;
  /** Цена до проскальзывания. Существует только в момент матчинга. */
  readonly baseOpen: number;
  readonly slippageBps: number;
  /** Всегда положительный размер; знак движения позиции несёт `side`. */
  readonly qty: number;
  readonly fee: number;
  readonly side: FillSide;
  readonly fillKind?: 'open' | 'add' | 'close' | 'protection';
}

/** Funding-расчёт в журнале. `rate` и `covered` не выводимы ни из чего — записываются резолвером. */
export interface ActorJournalFunding {
  readonly kind: 'funding';
  readonly frontier: number;
  readonly tsUs: TimestampUs;
  readonly rate: number;
  readonly covered: boolean;
  /** Положительное значение — расход (соглашение движкового `FundingSettlement`). */
  readonly cost: number;
}

/** Запись журнала бухгалтерии. Порядок в массиве и есть порядок применения. */
export type ActorJournalEntry = ActorJournalFill | ActorJournalFunding;

/**
 * Причина закрытия и запрошенная доля — ЕДИНСТВЕННОЕ, что хост приносит про сделку.
 *
 * Тип движковый, а не одноимённая копия: копия разошлась бы ровно тогда, когда движок добавит поле,
 * — и разошлась бы молча, потому что структурная совместимость лишнего поля не замечает. `0.9.0`
 * добавил `closeFraction`, и локальное объявление продолжало бы компилироваться, роняя долю на
 * границе.
 */
export type ActorCloseAnnotation = CloseAnnotation;

/**
 * Точка equity — ОДНА НА КАЖДЫЙ frontier, без пропусков.
 *
 * Полнота обязательна, и цена её нарушения известна заранее: `effectiveElapsedYears` считает
 * прошедшее время ПО КРИВОЙ EQUITY, а не по запрошенному окну. Пропущенные точки не «немного
 * огрубят график» — они сожмут знаменатель годовой доходности и завысят cagr/calmar молча.
 * Метки времени здесь нет намеренно: она берётся у frontier'а по номеру, и разойтись им негде.
 */
export interface ActorEquitySample {
  readonly frontier: number;
  readonly equity: number;
}

/**
 * Всё, что горячий раннер обязан записать за один прогон одного символа.
 *
 * `finalLedger` — ЯКОРЬ СВЕРКИ, а не удобство. Проекция сворачивает журнал движковыми функциями и
 * требует совпадения с этим значением ПОЛНОСТЬЮ, включая массив филлов поле в поле. Без якоря
 * агрегат был бы набором списков, про которые никто не проверяет, что они описывают одну историю.
 */
export interface ActorExecutionRecord {
  /**
   * Идентификатор ИНСТАНСА актора. Обязателен уже здесь, а не при агрегации нескольких символов:
   * восстановить его снаружи можно было бы только по `symbol`, а это неверно ровно тогда, когда
   * акторов на символ больше одного. `seq` и `subscriptionId` актор-локальны, и без этого поля две
   * записи склеились бы в одну историю с пересекающимися номерами.
   */
  readonly actorId: string;
  readonly symbol: string;
  /**
   * ФАКТИЧЕСКИЕ подписки, с которыми актор был создан, — тот же список, что уехал в
   * `ActorInit.subscriptions`. Не реконструкция по манифесту: реконструкция отвечала бы на вопрос
   * «что было объявлено», а нужен ответ «что было разрешено и доставлено».
   */
  readonly subscriptions: readonly ActorSubscriptionDescriptor[];
  readonly frontiers: readonly ActorFrontierRecord[];
  readonly orders: readonly ActorOrderRecord[];
  /** Единая упорядоченная последовательность бухгалтерии: филлы и funding вперемешку, как было. */
  readonly journal: readonly ActorJournalEntry[];
  readonly closes: readonly ActorCloseAnnotation[];
  readonly equity: readonly ActorEquitySample[];
  /** Вердикты хостового RiskEngine. `barIndex` каждого — номер frontier'а. */
  readonly riskDecisions: readonly RiskDecision[];
  /**
   * Принудительное закрытие по концу данных: номер frontier'а и цена валюации.
   *
   * Метки времени здесь нет намеренно — она берётся у frontier'а. Синтетический филл строит ДВИЖОК
   * (`deriveActorTrades`), хост не вправе его сочинять.
   */
  readonly forcedExit?: { readonly frontier: number; readonly price: number };
  readonly finalLedger: Ledger;
  /**
   * Append-only поток диспетчеризации — ОБЯЗАТЕЛЕН, а не опционален.
   *
   * Успешный actor-прогон без потока не принимается: отвергнутая командой не оставляет следа
   * больше НИГДЕ — ни заявки, ни филла, ни сделки, — и «прогон прошёл, журнала нет» неотличимо от
   * «ничего не отвергалось». Форма и гарды живут в `timeline.ts`.
   */
  readonly timeline: ActorTimeline;
}

/** Форма филла для движковых функций — проекция сворачивает записанное ИМИ, а не своей копией. */
export function ledgerFillOf(record: ActorJournalFill): Fill {
  return {
    fillId: record.fillId,
    tsUs: record.tsUs,
    price: record.price,
    qty: record.qty,
    side: record.side,
    fee: record.fee,
    causedBy: record.orderId,
  };
}
