// Сериализуемая спека прогона для барного цикла в отдельном потоке.
//
// ГЛАВНОЕ ПРОЕКТНОЕ РЕШЕНИЕ: через границу потока едет РЕЦЕПТ, а не данные.
//
// `RunDeps` держит живые объекты — реестр модулей, роутер с исполнителями, ленту с методами. Ни
// один из них не переживает `postMessage`: structured clone копирует данные, но не замыкания и не
// нативные дескрипторы. Копировать же саму ленту (десятки мегабайт свечей на реальном прогоне)
// пришлось бы на каждый запуск, и выигрыш от переноса цикла съело бы копирование.
//
// Поэтому поток получает описание того, ЧТО построить, и строит это сам: открывает свой порт
// данных, материализует ленту, собирает реестр и роутер. Всё, что здесь перечислено, — простые
// данные, которые structured clone переносит без потерь.
//
// Зачем перенос вообще нужен — две независимые причины:
//   1) `worker.ts` (P3-5): барный цикл CPU-bound и не отдаёт управление, поэтому голодает хартбит
//      лизы; длинный universe-прогон может отпустить лизу, и другой воркер переисполнит задачу.
//      Митигация сегодня — продление лизы перед входом в цикл; структурное закрытие — вынос цикла
//      с главного потока, где таймеры смогут тикать.
//   2) синхронный вызов в изолят (`evalClosureSync`) снимает измеренные ~150 мкс/бар штрафа
//      асинхронного пути (bt#191/196), но блокирует поток на время хука. В отдельном потоке эта
//      блокировка никого не задевает.
//
// ПОПРАВКА К «РЕЦЕПТУ, А НЕ ДАННЫМ». Написанное выше верно для станков, но не для прода, и это
// выяснилось замером. Главный поток строит ленту в любом случае — `dsFingerprint` считается ДО
// прогона и кормит дедуп-гейт, — поэтому «поток строит свою» означало бы вторую постройку тех же
// данных мимо `overlayTapeCache`. Значит через границу всё-таки едут данные; вопрос лишь в форме, и
// замер bt#199 её выбрал: колонки типизированных массивов против канонических строк — 2.9 МБ и 1 мс
// против 12.5 МБ и 164–211 мс на 60 тыс. строк. Отсюда второй вариант `ThreadDataPortSpec`.

import type { OverlayRouterSpec } from '../sandbox/overlay-router-spec.js';
import type { TapeColumns } from '../tape-columns.js';

/**
 * Откуда поток берёт свечи.
 *
 * `columns` — ПРОД-вариант: лента уже материализована на главном потоке (её строит `materializeFor`
 * до прогона, чтобы посчитать `dsFingerprint` для дедуп-гейта), и через границу едет её колоночный
 * двойник. `fixture` — вариант станков и тестов, где поток открывает каталог фикстур сам.
 *
 * Почему прод не может пойти путём `fixture`. Порт данных в проде — не каталог на диске, а клиент
 * платформы с авторизацией и ретраями; передать «рецепт» его постройки одними простыми данными
 * нельзя, а если бы и можно было — поток прочитал бы источник ВТОРОЙ раз, в обход `overlayTapeCache`
 * и мимо уже посчитанного отпечатка. Поэтому прод отдаёт данные, а не рецепт.
 */
export type ThreadDataPortSpec =
  | {
      readonly kind: 'fixture';
      /** Каталог фикстур (`FixtureDataPort`). */
      readonly dir: string;
    }
  | {
      readonly kind: 'columns';
      /**
       * Колонки уже материализованной ленты (`engine/tape-columns.ts`). Едут КОПИЕЙ, без
       * `transferList`: колонки лежат в разделяемом `overlayTapeCache`, а перенос отсоединил бы
       * буферы у отправителя и молча опустошил бы запись кэша для следующего прогона.
       */
      readonly columns: TapeColumns;
    };

/**
 * Что материализовать в ленту (аргументы `buildOverlayDataset`). Нужен ТОЛЬКО варианту `fixture` —
 * у `columns` датасет и таймфрейм уже внутри самих колонок, и отдельного поля им не полагается
 * именно для того, чтобы не возникло пары «колонки от одной ленты, метки от другой».
 */
export interface ThreadDatasetSpec {
  readonly datasetRef: string;
  readonly symbols: readonly string[];
  readonly timeframe: string;
  readonly period: { readonly from: string; readonly to: string };
}

/** Флаги прогона — подмножество `RunDeps`, состоящее ТОЛЬКО из простых данных. */
export interface ThreadRunFlags {
  readonly barBatching?: { readonly maxBars: number };
  readonly barMajor?: boolean;
  readonly barMajorBatch?: boolean;
  // `contextFreeze` здесь СОЗНАТЕЛЬНО отсутствует: `StrategyRunDeps` его не принимает, и прод-ветка
  // стратегии его не передаёт. Держать knob, который ничего не делает, — верный способ однажды
  // «включить» его и потратить день на выяснение, почему ничего не изменилось.
  /**
   * `RunDeps.universe` — НЕ то же самое, что `universe` в описании роутера, и путать их нельзя.
   * Здесь потолок числа символов (`maxN`), которым раннер ограничивает набор; там фактическое `n`
   * этого прогона, по которому масштабируется память сессии песочницы. Прод передаёт оба, каждое
   * своему потребителю, — значит и спека обязана нести оба.
   */
  readonly universe?: {
    readonly enabled: boolean;
    readonly maxN: number;
    readonly memBaseMb: number;
    readonly memPerSymbolMb: number;
  };
}

/** Полная спека: всё, что нужно потоку, чтобы собрать зависимости и выполнить прогон. */
export interface ThreadRunSpec {
  /** `BacktestRunRequest` как простые данные (пришёл из JSON, туда же и уедет). */
  readonly request: unknown;
  /** Каталог материализованного бандла стратегии на диске — поток читает его сам. */
  readonly bundleDir: string;
  /**
   * ОПИСАНИЕ роутера, посчитанное на главном потоке (`overlayRouterSpecFor`), а не собранное здесь.
   *
   * Раньше на этом месте стоял один `sandboxBackend`, а остальное поток добирал из своего
   * `loadConfig()` — и терял том режима DooD вместе с universe-масштабированием. Теперь конфигурация
   * ровно одна и едет целиком; собрать её иначе, чем главный поток, стало невозможно.
   */
  readonly router: OverlayRouterSpec;
  readonly dataPort: ThreadDataPortSpec;
  /** Обязателен для `dataPort.kind === 'fixture'`; при `columns` игнорируется (метки внутри колонок). */
  readonly dataset?: ThreadDatasetSpec;
  readonly flags?: ThreadRunFlags;
}

/**
 * Ответ потока.
 *
 * Ошибка едет разобранной на строки, а не объектом `Error`: structured clone переносит `Error`, но
 * не подклассы и не собственные поля, и на той стороне типизированная ошибка молча выродилась бы в
 * безымянную. Лучше явная пара «сообщение + стек», чем незаметная потеря типа.
 */
export type ThreadRunReply =
  | { readonly ok: true; readonly result: unknown; readonly sandboxErrors: readonly unknown[] }
  | { readonly ok: false; readonly message: string; readonly stack?: string };
