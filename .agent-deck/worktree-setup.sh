#!/usr/bin/env bash
# Обёртка Agent Deck. Логики здесь нет намеренно: она в scripts/worktree-init.sh, чтобы
# разработка не была завязана на деку — уйдёшь в другой менеджер сессий, удалишь этот
# каталог, и бутстрап продолжит работать из любой оболочки.
#
# Дека запускает скрипт с cwd = только что созданное дерево; путь передаём явно.
# Требует однократного `agent-deck worktree trust-scripts .` — дека хеширует файл и
# спрашивает согласие заново после каждой его правки.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
exec "$root/scripts/worktree-init.sh" "$PWD"
